/* Original PNG lookup for hideout inspectors; never replaces or resizes 48px icons. */
const fs=require('fs'),path=require('path'),vm=require('vm'),crypto=require('crypto'),os=require('os');
const root=path.resolve(__dirname,'..'),folder=path.join(root,'assets/item-details');
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const posix=p=>p.split(path.sep).join('/');
async function build(){
 const c=vm.createContext({});for(const f of ['config.js','data.js','attachment-data.js'])vm.runInContext(fs.readFileSync(path.join(root,'js',f),'utf8'),c);
 const {items,gear}=vm.runInContext('({items:ITEMS,gear:ART.gear})',c);
 const wanted=new Set([...items.map(i=>'items/'+(i.iconId||i.id)),...gear.map(id=>'gear/'+id)]),sources=new Map();
 const add=(file)=>{const id=path.basename(file,'.png'),key=wanted.has('gear/'+id)?'gear/'+id:'items/'+id;if(wanted.has(key))sources.set(key,posix(path.relative(root,file)));};
 const batches=path.join(root,'assets/item-art');
 for(const batch of fs.readdirSync(batches).sort()){
  const dir=path.join(batches,batch,'sources');if(fs.existsSync(dir))for(const f of fs.readdirSync(dir).sort())if(f.endsWith('.png'))add(path.join(dir,f));
 }
 // Recover the first batch by its recorded filenames, then keep it inside the project.
 const gm=JSON.parse(fs.readFileSync(path.join(root,'assets/gear-prompts.json'))),im=JSON.parse(fs.readFileSync(path.join(root,'assets/item-icon-prompts.json')));
 const session=gm.sourceDirectory.split('/').at(-1),cache=path.join(os.homedir(),'.codex/generated_images',session);
 for(const [group,rows]of [['items',im.items],['gear',gm.icons]])for(const row of rows){
  const key=group+'/'+row.id;if(!wanted.has(key)||sources.has(key))continue;
  const archived=row.sourceArchive&&path.join(root,row.sourceArchive),cached=path.join(cache,row.source||'');
  let src=archived&&fs.existsSync(archived)?archived:fs.existsSync(cached)?cached:null;
  if(src){const dest=path.join(batches,'legacy/sources',row.id+'.png');if(src===cached){fs.mkdirSync(path.dirname(dest),{recursive:true});fs.copyFileSync(src,dest);src=dest;}sources.set(key,posix(path.relative(root,src)));}
 }
 for(const batch of ['arsenal-v1','attachments-v1']){const dir=path.join(root,'design/weapons',batch,'art/sources');if(fs.existsSync(dir))for(const f of fs.readdirSync(dir).sort())if(f.endsWith('.png'))add(path.join(dir,f));}
 const manifest=path.join(folder,'catalog.json'),assets=[];fs.mkdirSync(folder,{recursive:true});
 for(const [key,source]of [...sources].sort(([a],[b])=>a.localeCompare(b))){
  const data=fs.readFileSync(path.join(root,source));
  if(data.subarray(1,4).toString()!=='PNG')throw new Error('Not a PNG original: '+source);
  assets.push({key,source,target:source,sourceHash:hash(data),width:data.readUInt32BE(16),height:data.readUInt32BE(20)});
 }
 assets.sort((a,b)=>a.key.localeCompare(b.key));
 const missing=[...wanted].filter(k=>!sources.has(k)).sort(),catalog={format:'original-png',resize:false,preload:false,assets,missing};
 fs.writeFileSync(manifest,JSON.stringify(catalog,null,2)+'\n');
 fs.writeFileSync(path.join(root,'js/detail-art.js'),'/* Generated by tools/build-detail-art.js; native-size originals, loaded only by inspectors. */\nconst DETAIL_ART = '+JSON.stringify(Object.fromEntries(assets.map(a=>[a.key,a.target])),null,2)+';\n');
 console.log(`Detail art: ${assets.length} native-size originals; ${missing.length} icon fallbacks; no image preload`);
}
build().catch(e=>{console.error(e);process.exitCode=1;});
