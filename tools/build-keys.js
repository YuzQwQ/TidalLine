/* One catalog supplies runtime items and the map editor's key selector. */
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
function build(){
  const keys=JSON.parse(fs.readFileSync(path.join(root,'design/items/keys.json'),'utf8'));
  const ids=new Set(),numbers=new Set();
  for(const k of keys){
    if(k.cat!=='key'||!k.id||ids.has(k.id)||!k.number||numbers.has(k.number)||!Number.isInteger(k.maxDur)||k.maxDur<1||!Number.isFinite(k.price)||k.price<0)throw Error('钥匙配置非法：'+k.id);
    ids.add(k.id);numbers.add(k.number);
  }
  const start='/* BEGIN GENERATED KEYS */',end='/* END GENERATED KEYS */';
  const file=path.join(root,'js/data.js'),source=fs.readFileSync(file,'utf8');
  const block=start+'\nconst KEY_ITEMS = '+JSON.stringify(keys)+';\n'+end;
  const a=source.indexOf(start),b=source.indexOf(end);
  if(a>=0&&b<a)throw Error('钥匙生成区块不完整');
  const next=a<0?source.replace('const ITEMS = [',block+'\n\nconst ITEMS = [\n  ...KEY_ITEMS,'):source.slice(0,a)+block+source.slice(b+end.length);
  if(!next.includes('...KEY_ITEMS,'))throw Error('缺少钥匙物品入口');
  fs.writeFileSync(file,next);
  fs.writeFileSync(path.join(root,'design/maps/shared/key-catalog.js'),'/* Generated by tools/build-keys.js; edit design/items/keys.json. */\n(function(root){const keys='+JSON.stringify(keys)+';if(typeof module!=="undefined"&&module.exports)module.exports=keys;else root.KeyCatalog=keys;})(typeof globalThis!=="undefined"?globalThis:this);\n');
  console.log('已同步钥匙：'+keys.length+' 种');return keys;
}
module.exports={build};if(require.main===module)build();
